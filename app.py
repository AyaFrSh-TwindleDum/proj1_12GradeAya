import steamlit as st
import numpy as np
import pandas as pd
import streamlit as st

# הגדרת עיצוב העמוד
st.set_page_config(
    page_title="חוזה ציוני סרטי באטמן",
    page_icon="🦇",
    layout="centered",
    initial_sidebar_state="expanded",
)

# 1. כותרת ראשית והסבר על הפרויקט (דרישה a)
st.title("🦇 חוזה ציוני סרטי באטמן")
st.subheader("פרויקט רגרסיה ליניארית אינטראקטיבי")

st.markdown("""
ברוכים הבאים לאפליקציית החיזוי! 
אפליקציה זו מדגימה תהליך מקצה לקצה של למידת מכונה (Machine Learning) על דאטה-סט של סרטי באטמן מ-Kaggle.

### 🎯 מה המודל חוזה ובאמצעות מה?
* **המשתנה שאותו רוצים לחזות ($y$):** ציון הקהל ב-IMDb (`Imdb Rating`).
* **המשתנה שממנו חוזים ($X$):** שנת יציאת הסרט לקולנוע (`Year`).
""")

st.divider()

# 2. הסבר על תהליך האימון והשוואת ה-Loss (דרישה c)
st.subheader("📚 תהליך אימון המודל והשוואת ביצועים")

st.markdown("""
תהליך האימון בוצע במחברת המחקר (Colab) דרך השלבים הבאים:
1. **טעינת הדאטה-סט:** הורדת נתוני סרטי באטמן מ-Kaggle וניקוי ערכים חסרים.
2. **הגדרת $X$ ו-$y$:** חילוץ שנת היציאה ($X$) וציון ה-IMDb ($y$) כמערכים נומריים.
3. **מודל בסיס (Baseline):** ניבוי קבוע לפי הממוצע של $y$ בלבד, ללא תלות ב-$X$.
4. **אימון רגרסיה ליניארית:** מציאת הקו הישר המיטבי $y = w \cdot X + b$ שממזער את השגיאה.
""")

# הצגת מדדי ה-Loss
col1, col2 = st.columns(2)
with col1:
  st.metric(
      label="📉 Baseline Loss (MAE)",
      value="0.7505",
      help="השגיאה הממוצעת כשמנבאים רק לפי הממוצע",
  )

with col2:
  st.metric(
      label="🚀 Model Loss (MAE)",
      value="0.7183",
      delta="-4.3% (שיפור בשגיאה)",
      delta_color="normal",
      help="השגיאה הממוצעת של מודל הרגרסיה הליניארית",
  )

st.info("""
**משוואת קו הרגרסיה שהתקבלה מהאימון:**
$$\text{IMDb Rating} = 0.0226 \times \text{Year} - 38.1322$$

* **משמעות ה-Slope ($w \approx 0.0226$):** בכל שנה שעוברת, ציון הסרט עולה בממוצע ב-0.0226 נקודות (מגמת שיפור קלה לאורך השנים).
* **משמעות ה-Intercept ($b \approx -38.1322$):** נקודת החיתוך המתמטית עם ציר ה-$y$.
""")

st.divider()

# 3. ממשק החיזוי האינטראקטיבי (דרישה b)
st.subheader("🎯 סימולטור חיזוי אינטראקטיבי")
st.write(
    "הזינו שנת יציאה של סרט (או השתמשו בסליידר/חיצים) וקבלו את החיזוי של"
    " המודל:"
)

# קלט מהמשתמש
year_input = st.number_input(
    "בחר/י שנת יציאה (Year):",
    min_value=1930,
    max_value=2050,
    value=2024,
    step=1,
)

# פרמטרי המודל המאומן מהמחברת
w = 0.02262446
b = -38.13222304

# חישוב הניבוי לפי $y = w * X + b$
predicted_rating = w * year_input + b
# הגבלה לטווח הגיוני של ציוני IMDb (1 עד 10)
clamped_rating = min(max(predicted_rating, 1.0), 10.0)

# הצגת התוצאה
st.success(f"""
### 🎬 ציון IMDb משוער לסרט בשנת {year_input}:
# **{clamped_rating:.2f} / 10**
""")

st.caption(
    "💡 **הסבר על התוצאה:** החיזוי מחושב ישירות על ידי הכפלת השנה ב-0.0226"
    " וחיסור 38.1322, בהתאם לפרמטרים שנלמדו באימון."
)
